import fs from 'fs';
import path from 'path';
import { ProjectAnalysis } from '../engine/types.js';

export function generateSkillAndArtifacts(rootPath: string, analysis: ProjectAnalysis): {
  skillPath: string;
  cachePath: string;
} {
  const absoluteRoot = path.resolve(rootPath);
  
  // 1. Ensure .feinman and .agents/skills/feinman directories exist
  const feinmanDir = path.join(absoluteRoot, '.feinman');
  const skillsDir = path.join(absoluteRoot, '.agents', 'skills', 'feinman');
  
  if (!fs.existsSync(feinmanDir)) fs.mkdirSync(feinmanDir, { recursive: true });
  if (!fs.existsSync(skillsDir)) fs.mkdirSync(skillsDir, { recursive: true });

  // 2. Build SKILL.md content
  const skillMarkdown = `---
name: feinman-codebase-guide
description: "Navigate, explain, trace execution flows, and plan code changes for ${analysis.name} using Feinman's codebase intelligence."
---

# Feinman Codebase Guide: ${analysis.name}

> Generated by Feinman — Codebase Understanding for Humans and AI Agents.
> Repository: \`${analysis.rootPath}\` | Primary Language: ${analysis.primaryLanguage} | Files: ${analysis.fileCount}

---

## 1. Project Purpose & Mental Model

${analysis.whatIsThis.summary}

### Mental Model
${analysis.howItWorks.mentalModel}

---

## 2. Quickstart & Verification Commands

| Action | Command | Verified Source |
|---|---|---|
| **Install** | \`${analysis.whatIsThis.quickstart.installCmd}\` | Package Manifest |
| **Dev Server** | \`${analysis.whatIsThis.quickstart.devCmd}\` | Scripts Configuration |
| **Run Tests** | \`${analysis.whatIsThis.quickstart.testCmd}\` | Test Runner (${analysis.howToMaintain.testFramework}) |
${analysis.whatIsThis.quickstart.buildCmd ? `| **Build** | \`${analysis.whatIsThis.quickstart.buildCmd}\` | Production Build |\n` : ''}

---

## 3. Subsystems & Directory Map

${analysis.howItWorks.subsystems.map(s => `### ${s.name} (\`${s.id}\`)
- **Primary Role**: ${s.description}
- **Key Responsibilities**:
${s.responsibilities.map(r => `  - ${r}`).join('\n')}
- **Key Files**: ${s.files.slice(0, 5).map(f => `\`${f}\``).join(', ')}
`).join('\n')}

---

## 4. Entry Points
${analysis.whatIsThis.entryPoints.map(e => `- \`${e.file}\`: ${e.description}${e.isPrimary ? ' *(Primary Entrypoint)*' : ''}`).join('\n')}

---

## 5. How to Make Changes Safely

When modifying this codebase, follow the Feinman 4-step change discipline:
1. **Identify the Core Workbench**: Check which subsystem owns the logic.
2. **Inspect Downstream Blast Radius**: Find which files import the target module before modifying exported signatures.
3. **Keep Interface Boundaries Intact**: Don't leak implementation details across subsystems.
4. **Run Verified Tests**: Execute \`${analysis.howToMaintain.testCommand}\` to verify that existing contracts remain valid.

---

## 6. Feinman MCP Tools Reference

When connected to the Feinman MCP server, invoke these tools:
- \`feinman_understand_project\`: High-level plain English summary and architecture.
- \`feinman_explain_file\`: Plain English role and mental model for any specific file.
- \`feinman_trace_feature\`: Cross-file feature trace (e.g. auth, api, storage).
- \`feinman_plan_change\`: Exact files to modify, blast radius, and checklist for any user request.
- \`feinman_walkthrough\`: Progressive step-by-step tour of the repository.
`;

  // Write SKILL.md to .agents/skills/feinman/SKILL.md
  const skillPath = path.join(skillsDir, 'SKILL.md');
  fs.writeFileSync(skillPath, skillMarkdown, 'utf-8');

  // Also duplicate into .feinman/SKILL.md
  fs.writeFileSync(path.join(feinmanDir, 'SKILL.md'), skillMarkdown, 'utf-8');

  // 3. Write persistent intelligence cache (.feinman/feinman.json)
  const cachePath = path.join(feinmanDir, 'feinman.json');
  fs.writeFileSync(cachePath, JSON.stringify(analysis, null, 2), 'utf-8');

  // 4. Generate MCP client configuration snippets (.feinman/mcp-config.json)
  const mcpConfig = {
    mcpServers: {
      feinman: {
        command: "feynstart",
        args: ["--mcp", absoluteRoot],
        env: {}
      }
    }
  };
  fs.writeFileSync(path.join(feinmanDir, 'mcp-config.json'), JSON.stringify(mcpConfig, null, 2), 'utf-8');

  return {
    skillPath,
    cachePath,
  };
}
